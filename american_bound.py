import numpy as np
import tensorflow as tf
import gc


r = 0.0
c = 0.02
T = 2.0
X0 = 1.0


def get_heterogeneous_params(d=20, seed=42):
    np.random.seed(seed)

    sigmas = np.loadtxt("/content/drive/MyDrive/volatilities_2000_2017(new).csv", delimiter=",")
    sigmas = sigmas.flatten()

    corr_matrix = np.loadtxt("/content/drive/MyDrive/correlation_matrix_2000_2017(new).csv", delimiter=",")

    if len(sigmas) != d:
        raise ValueError(f"Sigma length {len(sigmas)} does not match d={d}")
    if corr_matrix.shape != (d, d):
        raise ValueError(f"Correlation matrix shape {corr_matrix.shape} does not match ({d},{d})")

    # Normalize to proper correlation matrix
    D = np.diag(1.0 / np.sqrt(np.diag(corr_matrix)))
    corr_matrix = D @ corr_matrix @ D
    np.fill_diagonal(corr_matrix, 1.0)

    return sigmas.astype(np.float32), corr_matrix.astype(np.float32)

def make_cov_matrix(sigmas, corr_matrix):
    """Construct covariance matrix cov_ij = sigma_i sigma_j rho_ij"""
    d = len(sigmas)
    cov = np.zeros((d, d), dtype=np.float32)
    for i in range(d):
        for j in range(d):
            cov[i, j] = sigmas[i] * sigmas[j] * corr_matrix[i, j]
    return cov


def basket_payoff_tf(x, K):
    avg = tf.reduce_mean(x, axis=1, keepdims=True)
    return tf.nn.relu(avg - K)

def basket_payoff_np(x, K):
    avg = np.mean(x, axis=1, keepdims=True)
    return np.maximum(avg - K, 0.0).astype(np.float32)


class DGMNet(tf.keras.Model):
    def __init__(self, layer_width, n_layers, input_dim, seed=None):
        super().__init__()
        self.layer_width = layer_width
        self.n_layers = n_layers
        self.input_dim = input_dim

        if seed is not None:
            tf.random.set_seed(seed)

        initializer = tf.keras.initializers.GlorotUniform(seed=seed)

        self.W1 = self.add_weight(name="W1", shape=(input_dim + 1, layer_width), initializer=initializer)
        self.b1 = self.add_weight(name="b1", shape=(1, layer_width), initializer='zeros')

        self.Uz, self.Ug, self.Ur, self.Uh = [], [], [], []
        self.Wz, self.Wg, self.Wr, self.Wh = [], [], [], []
        self.bz, self.bg, self.br, self.bh = [], [], [], []

        for l in range(n_layers):
            self.Uz.append(self.add_weight(name=f"Uz{l}", shape=(input_dim + 1, layer_width), initializer=initializer))
            self.Ug.append(self.add_weight(name=f"Ug{l}", shape=(input_dim + 1, layer_width), initializer=initializer))
            self.Ur.append(self.add_weight(name=f"Ur{l}", shape=(input_dim + 1, layer_width), initializer=initializer))
            self.Uh.append(self.add_weight(name=f"Uh{l}", shape=(input_dim + 1, layer_width), initializer=initializer))

            self.Wz.append(self.add_weight(name=f"Wz{l}", shape=(layer_width, layer_width), initializer=initializer))
            self.Wg.append(self.add_weight(name=f"Wg{l}", shape=(layer_width, layer_width), initializer=initializer))
            self.Wr.append(self.add_weight(name=f"Wr{l}", shape=(layer_width, layer_width), initializer=initializer))
            self.Wh.append(self.add_weight(name=f"Wh{l}", shape=(layer_width, layer_width), initializer=initializer))

            self.bz.append(self.add_weight(name=f"bz{l}", shape=(1, layer_width), initializer='zeros'))
            self.bg.append(self.add_weight(name=f"bg{l}", shape=(1, layer_width), initializer='zeros'))
            self.br.append(self.add_weight(name=f"br{l}", shape=(1, layer_width), initializer='zeros'))
            self.bh.append(self.add_weight(name=f"bh{l}", shape=(1, layer_width), initializer='zeros'))

        self.W_out = self.add_weight(name="W_out", shape=(layer_width, 1), initializer=initializer)
        self.b_out = self.add_weight(name="b_out", shape=(1, 1), initializer='zeros')

    def call(self, t, x):
        X = tf.concat([t, x], axis=1)
        S = tf.nn.tanh(tf.matmul(X, self.W1) + self.b1)

        for l in range(self.n_layers):
            Z = tf.nn.tanh(tf.matmul(X, self.Uz[l]) + tf.matmul(S, self.Wz[l]) + self.bz[l])
            G = tf.nn.sigmoid(tf.matmul(X, self.Ug[l]) + tf.matmul(S, self.Wg[l]) + self.bg[l])
            R = tf.nn.sigmoid(tf.matmul(X, self.Ur[l]) + tf.matmul(S, self.Wr[l]) + self.br[l])
            H = tf.nn.tanh(tf.matmul(X, self.Uh[l]) + tf.matmul(S * R, self.Wh[l]) + self.bh[l])
            S = (1 - G) * H + Z * S

        return tf.matmul(S, self.W_out) + self.b_out


def generate_B1_batch(model, M, d, K):
    t = tf.random.uniform((M, 1), 0.0, T)
    x = tf.random.uniform((M, d), 0.0, 2.0)
    u = model(t, x)
    g_vals = basket_payoff_tf(x, K)
    mask = tf.squeeze(u > g_vals)
    return tf.boolean_mask(t, mask), tf.boolean_mask(x, mask)

def generate_B2_batch(model, M, d, K):
    t = tf.random.uniform((M, 1), 0.0, T)
    x = tf.random.uniform((M, d), 0.0, 2.0)

    idxs = tf.random.uniform((M,), 0, d, dtype=tf.int32)
    one_hot_mask = tf.one_hot(idxs, depth=d, dtype=tf.float32)
    binary_vals = tf.cast(tf.random.uniform((M,), 0, 1) > 0.5, tf.float32) * 2.0
    binary_vals = tf.reshape(binary_vals, (-1, 1))
    binary_vals = tf.broadcast_to(binary_vals, (M, d))
    x = x * (1 - one_hot_mask) + binary_vals * one_hot_mask

    u = model(t, x)
    g_vals = basket_payoff_tf(x, K)
    mask = tf.squeeze(u <= g_vals)
    return tf.boolean_mask(t, mask), tf.boolean_mask(x, mask)

def generate_B3_batch(M, d):
    t = tf.ones((M, 1), dtype=tf.float32) * T
    x = tf.random.uniform((M, d), 0.0, 2.0)
    return t, x

def pad_batch(t, x, batch_size):
    current_size = tf.shape(t)[0]
    if current_size >= batch_size:
        return t[:batch_size], x[:batch_size]
    pad_size = batch_size - current_size
    t_pad = tf.random.uniform((pad_size, 1), 0, T)
    x_pad = tf.random.uniform((pad_size, tf.shape(x)[1]), 0, 2.0)
    return tf.concat([t, t_pad], axis=0), tf.concat([x, x_pad], axis=0)


@tf.function
def loss_fn(model, t1, x1, t2, x2, t3, x3, cov, K):
    with tf.GradientTape(persistent=True) as tape:
        tape.watch([t1, x1, t2, x2, t3, x3])

        u1 = model(t1, x1)
        u1_t = tape.gradient(u1, t1)
        u1_x = tape.gradient(u1, x1)

        u1_xx = 0.0
        d = x1.shape[1]
        for i in range(d):
            for j in range(d):
                grad_i = u1_x[:, i:i+1]
                grad2_ij = tape.gradient(grad_i, x1)[:, j:j+1]
                u1_xx += 0.5 * cov[i, j] * x1[:, i:i+1] * x1[:, j:j+1] * grad2_ij

        drift = tf.reduce_sum((r - c) * x1 * u1_x, axis=1, keepdims=True)
        pde_residual = u1_t + drift + u1_xx - r * u1

        u2 = model(t2, x2)
        g2 = basket_payoff_tf(x2, K)
        free_boundary_penalty = tf.nn.relu(g2 - u2)

        u3 = model(t3, x3)
        g3 = basket_payoff_tf(x3, K)
        terminal_penalty = u3 - g3

    del tape

    loss1 = tf.reduce_mean(tf.square(pde_residual))
    loss2 = tf.reduce_mean(tf.square(free_boundary_penalty))
    loss3 = tf.reduce_mean(tf.square(terminal_penalty))
    return loss1 + loss2 + loss3

@tf.function
def train_step(model, optimizer, t1, x1, t2, x2, t3, x3, cov, K):
    with tf.GradientTape() as tape:
        loss = loss_fn(model, t1, x1, t2, x2, t3, x3, cov, K)
    grads = tape.gradient(loss, model.trainable_variables)
    optimizer.apply_gradients(zip(grads, model.trainable_variables))
    return loss


def get_learning_rate(step):
    if step <= 5000:
        return 1e-4
    elif step <= 10000:
        return 5e-4
    elif step <= 20000:
        return 1e-5
    elif step <= 30000:
        return 5e-6
    elif step <= 40000:
        return 1e-6
    elif step <= 45000:
        return 5e-7
    else:
        return 1e-7



@tf.function
def _pde_integrand_hutchinson(model, t, x, cov_tf, r, c, n_probe=1):
    """
    I = f_t + (r-c) x·f_x + 0.5 Tr(A H) - r f
    where A = diag(x) cov diag(x), H = Hessian_x f
    Compute 0.5 Tr(AH) via Hutchinson: E[z^T A H z], using HVPs.
    """
    batch = tf.shape(x)[0]
    d = tf.shape(x)[1]

    trace_est = tf.zeros((batch, 1), dtype=tf.float32)

    with tf.GradientTape(persistent=True) as tape2:
        tape2.watch([t, x])


        with tf.GradientTape(persistent=True) as tape1:
            tape1.watch([t, x])
            f = model(t, x)


        f_t, f_x = tape1.gradient(f, [t, x])
        del tape1

        drift = (r - c) * tf.reduce_sum(x * f_x, axis=1, keepdims=True)

        for _ in tf.range(n_probe):
            z = tf.where(
                tf.random.uniform((batch, d)) < 0.5,
                tf.ones((batch, d), tf.float32),
                -tf.ones((batch, d), tf.float32),
            )

            grad_dot_z = tf.reduce_sum(f_x * z, axis=1, keepdims=True)
            Hv = tape2.gradient(grad_dot_z, x)  # H z

            xz = x * z
            cov_xz = tf.matmul(xz, cov_tf)
            Az = x * cov_xz

            trace_est += tf.reduce_sum(Az * Hv, axis=1, keepdims=True)

    del tape2

    trace_est = trace_est / tf.cast(n_probe, tf.float32)
    diffusion = 0.5 * trace_est

    integrand = f_t + drift + diffusion - r * f
    return integrand, f

def compute_lower_upper_bounds(
    model,
    K,
    d,
    T,
    X0,
    r,
    c,
    sigmas,
    corr_matrix,
    cov_np,
    n_paths=512,
    dt=5e-3,
    n_probe=1,
    seed=123,
    batch_eval=256,
):
    """
    Lower: E[e^{-r tau} g(X_tau)], tau = first time f(t,X)<g(X) (strict)
    Upper: E[sup_t (e^{-rt} g(X_t) - M_t)], M from discretized (4.7)
    """
    dt = float(dt)
    tf.random.set_seed(seed)
    rng = np.random.default_rng(seed)

    n_steps = int(np.round(T / dt))
    times = np.linspace(0.0, T, n_steps + 1).astype(np.float32)

    L = np.linalg.cholesky(corr_matrix).astype(np.float32)
    X = np.full((n_paths, d), X0, dtype=np.float32)

    cov_tf = tf.convert_to_tensor(cov_np.astype(np.float32))

    exercised = np.zeros((n_paths,), dtype=bool)
    tau_payoff = np.zeros((n_paths,), dtype=np.float32)

    M = np.zeros((n_paths, 1), dtype=np.float32)
    sup_val = -1e30 * np.ones((n_paths, 1), dtype=np.float32)

    g0 = basket_payoff_np(X, K)
    sup_val = np.maximum(sup_val, np.exp(-r * 0.0) * g0 - M)

    sqrt_dt = np.sqrt(dt).astype(np.float32)
    drift_vec = (r - c - 0.5 * (sigmas ** 2)) * dt  # (d,)

    for n in range(n_steps):
        t_n = times[n]
        t_np = np.full((n_paths, 1), t_n, dtype=np.float32)

        integrand_list, f_list = [], []
        for start in range(0, n_paths, batch_eval):
            end = min(start + batch_eval, n_paths)
            xb = tf.convert_to_tensor(X[start:end], dtype=tf.float32)
            tb = tf.convert_to_tensor(t_np[start:end], dtype=tf.float32)
            I_b, f_b = _pde_integrand_hutchinson(model, tb, xb, cov_tf, r, c, n_probe=n_probe)
            integrand_list.append(I_b.numpy())
            f_list.append(f_b.numpy())
        I_n = np.vstack(integrand_list).astype(np.float32)
        f_n = np.vstack(f_list).astype(np.float32)

        Z = rng.standard_normal(size=(n_paths, d)).astype(np.float32)
        dW = sqrt_dt * (Z @ L.T).astype(np.float32)

        X = X * np.exp(drift_vec[None, :] + sigmas[None, :] * dW).astype(np.float32)

        t_np1 = np.full((n_paths, 1), times[n + 1], dtype=np.float32)
        f_np1_list = []
        for start in range(0, n_paths, batch_eval):
            end = min(start + batch_eval, n_paths)
            xb = tf.convert_to_tensor(X[start:end], dtype=tf.float32)
            tb = tf.convert_to_tensor(t_np1[start:end], dtype=tf.float32)
            f_np1_list.append(model(tb, xb).numpy())
        f_np1 = np.vstack(f_np1_list).astype(np.float32)

        M = M + (f_np1 - f_n) - I_n * dt

        g_np1 = basket_payoff_np(X, K)
        sup_val = np.maximum(sup_val, np.exp(-r * times[n + 1]) * g_np1 - M)

        newly = (~exercised) & (f_np1[:, 0] < g_np1[:, 0])
        if np.any(newly):
            tau_payoff[newly] = (np.exp(-r * times[n + 1]) * g_np1[newly, 0]).astype(np.float32)
            exercised[newly] = True

    not_ex = ~exercised
    if np.any(not_ex):
        gT = basket_payoff_np(X[not_ex], K)[:, 0]
        tau_payoff[not_ex] = (np.exp(-r * T) * gT).astype(np.float32)

    lower = float(np.mean(tau_payoff))
    upper = float(np.mean(sup_val))
    return lower, upper


def train_single_strike(
    K, d, cov_tf, cov_np, sigmas, corr_matrix, strike_idx,
    n_train_steps=2500
):
    print(f"\n{'='*60}")
    print(f"Training for Strike K = {K:.4f}")
    print(f"{'='*60}")

    np.random.seed(42 + strike_idx)
    tf.random.set_seed(42 + strike_idx)

    model = DGMNet(layer_width=100, n_layers=3, input_dim=d, seed=42 + strike_idx)
    optimizer = tf.keras.optimizers.Adam(learning_rate=1e-4)

    bound_cfg_quick = dict(
        n_paths=512,
        dt=5e-3,
        n_probe=1,
        seed=1000 + strike_idx,
        batch_eval=256
    )
    bound_cfg_final = dict(
        n_paths=2000,
        dt=5e-4,
        n_probe=1,
        seed=2000 + strike_idx,
        batch_eval=256
    )

    for step in range(n_train_steps):
        lr = get_learning_rate(step)
        optimizer.learning_rate.assign(lr)

        try:
            t1, x1 = generate_B1_batch(model, 12000, d, K)
            t1, x1 = pad_batch(t1, x1, 600)
        except Exception:
            t1 = tf.random.uniform((600, 1), 0.0, T)
            x1 = tf.random.uniform((600, d), 0.0, 2.0)

        try:
            t2, x2 = generate_B2_batch(model, 12000, d, K)
            t2, x2 = pad_batch(t2, x2, 600)
        except Exception:
            t2 = tf.random.uniform((600, 1), 0.0, T)
            x2 = tf.random.uniform((600, d), 0.0, 2.0)

        t3, x3 = generate_B3_batch(3600, d)

        loss = train_step(model, optimizer, t1, x1, t2, x2, t3, x3, cov_tf, K)

        if step % 500 == 0:
            t0 = tf.zeros((1, 1), dtype=tf.float32)
            x0 = tf.ones((1, d), dtype=tf.float32) * X0
            pred = float(model(t0, x0).numpy()[0, 0])

            lower_q, upper_q = compute_lower_upper_bounds(
                model=model,
                K=K,
                d=d,
                T=T,
                X0=X0,
                r=r,
                c=c,
                sigmas=sigmas,
                corr_matrix=corr_matrix,
                cov_np=cov_np,
                **bound_cfg_quick
            )

            print(
                f"Step {step:5d} | Loss {loss.numpy():.6f} | u(0,X0) {pred:.5f} "
                f"| LB {lower_q:.5f} | UB {upper_q:.5f}"
            )

    t0 = tf.zeros((1, 1), dtype=tf.float32)
    x0 = tf.ones((1, d), dtype=tf.float32) * X0
    nn_solution = float(model(t0, x0).numpy()[0, 0])

    lower_f, upper_f = compute_lower_upper_bounds(
        model=model,
        K=K,
        d=d,
        T=T,
        X0=X0,
        r=r,
        c=c,
        sigmas=sigmas,
        corr_matrix=corr_matrix,
        cov_np=cov_np,
        **bound_cfg_final
    )

    print(f"\nFinal u(0,X0): {nn_solution:.5f}")
    print(f"Final Lower bound: {lower_f:.5f}")
    print(f"Final Upper bound: {upper_f:.5f}")

    return model, nn_solution, lower_f, upper_f


