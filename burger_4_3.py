import numpy as np
import tensorflow as tf
import matplotlib.pyplot as plt
tf.keras.backend.set_floatx('float32')



T = 1.0
X_lo, X_hi = 0.0, 1.0
nu_range, alpha_range = [1e-2, 1e-1], [1e-2, 1.0]
a_range, b_range = [-1, 1], [-1, 1]

def initial_condition(x,a,b): return a+(b-a)*x
def boundary_value(is_left,a,b): return is_left*a+(1-is_left)*b


# Sampling

def sample_interior(N):
    t=tf.random.uniform([N,1],0,T)
    x=tf.random.uniform([N,1],X_lo,X_hi)
    nu=tf.random.uniform([N,1],*nu_range)
    alpha=tf.random.uniform([N,1],*alpha_range)
    a=tf.random.uniform([N,1],*a_range)
    b=tf.random.uniform([N,1],*b_range)
    return t,x,nu,alpha,a,b

def sample_boundary(N):
    t=tf.random.uniform([N,1],0,T)
    is_left=tf.cast(tf.random.uniform([N,1],0,1)>0.5,tf.float32)
    x=is_left*X_lo+(1-is_left)*X_hi
    nu=tf.random.uniform([N,1],*nu_range)
    alpha=tf.random.uniform([N,1],*alpha_range)
    a=tf.random.uniform([N,1],*a_range)
    b=tf.random.uniform([N,1],*b_range)
    return t,x,nu,alpha,a,b,is_left

def sample_initial(N):
    t=tf.zeros([N,1])
    x=tf.random.uniform([N,1],X_lo,X_hi)
    nu=tf.random.uniform([N,1],*nu_range)
    alpha=tf.random.uniform([N,1],*alpha_range)
    a=tf.random.uniform([N,1],*a_range)
    b=tf.random.uniform([N,1],*b_range)
    return t,x,nu,alpha,a,b




class DGMBlock(tf.keras.layers.Layer):
    def __init__(self,units):
        super().__init__()
        self.z=tf.keras.layers.Dense(units,activation='tanh')
        self.g=tf.keras.layers.Dense(units,activation='sigmoid')
        self.r=tf.keras.layers.Dense(units,activation='sigmoid')
        self.h=tf.keras.layers.Dense(units,activation='tanh')
    def call(self,X,S):
        Z=self.z(tf.concat([X,S],1))
        G=self.g(tf.concat([X,S],1))
        R=self.r(tf.concat([X,S],1))
        H=self.h(tf.concat([X,R*S],1))
        return (1-G)*H+Z*S

class DGMNet(tf.keras.Model):
    def __init__(self,units=240,layers=6):
        super().__init__()
        self.first=tf.keras.layers.Dense(units,activation='tanh')
        self.blocks=[DGMBlock(units) for _ in range(layers)]
        self.out=tf.keras.layers.Dense(1)
    def call(self,t,x,nu,alpha,a,b):
        X=tf.concat([t,x,nu,alpha,a,b],1)
        S=self.first(X)
        for blk in self.blocks:S=blk(X,S)
        return self.out(S)


# PDE residual u_t − νu_xx + αu u_x

def residual(model,t,x,nu,alpha,a,b):
    with tf.GradientTape(persistent=True) as t2:
        t2.watch([t,x])
        with tf.GradientTape(persistent=True) as t1:
            t1.watch([t,x])
            u=model(t,x,nu,alpha,a,b)
        u_t=t1.gradient(u,t)
        u_x=t1.gradient(u,x)
    u_xx=t2.gradient(u_x,x)
    del t1,t2
    return u_t - nu*u_xx + alpha*u*u_x


# Loss

def compute_loss(model,Ni,Nb,No):
    t_i,x_i,nu_i,al_i,a_i,b_i=sample_interior(Ni)
    r=residual(model,t_i,x_i,nu_i,al_i,a_i,b_i)
    loss_pde=tf.reduce_mean(tf.square(r))

    t_b,x_b,nu_b,al_b,a_b,b_b,left=sample_boundary(Nb)
    u_b=model(t_b,x_b,nu_b,al_b,a_b,b_b)
    u_bv=boundary_value(left,a_b,b_b)
    loss_bnd=tf.reduce_mean(tf.square(u_b-u_bv))

    t0,x0,nu0,al0,a0,b0=sample_initial(No)
    u0=model(t0,x0,nu0,al0,a0,b0)
    g0=initial_condition(x0,a0,b0)
    loss_ini=tf.reduce_mean(tf.square(u0-g0))

    return loss_pde+loss_bnd+loss_ini




def train(model,steps=40000,lr=3e-4):
    opt=tf.keras.optimizers.Adam(lr)
    for n in range(steps):
        with tf.GradientTape() as tape:
            loss=compute_loss(model,2048,512,512)
        grads=tape.gradient(loss,model.trainable_variables)
        opt.apply_gradients(zip(grads,model.trainable_variables))
        if n%500==0: print(f"Step {n:6d} | loss={loss.numpy():.3e}")




def burgers_fd(nu,alpha,a,b,Nx=1600,Nt=6000):
    x=np.linspace(0,1,Nx); dx=x[1]-x[0]
    u=a+(b-a)*x
    dt=min(0.25*dx*dx/nu,0.4*dx/(alpha*np.max(np.abs(u))+1e-6))
    Nt=int(T/dt)
    for _ in range(Nt):
        uxx=(u[2:]-2*u[1:-1]+u[:-2])/dx**2
        ux=(u[2:]-u[:-2])/(2*dx)
        u[1:-1]+=dt*(nu*uxx-alpha*u[1:-1]*ux)
        u[0],u[-1]=a,b
    return x,u




def plot_fig5(model):
    setups=[
        (0.01,0.95,0.9,-0.9),
        (0.02,0.95,0.9,-0.9),
        (0.01,0.95,-0.95,0.95),
        (0.02,0.9,0.9,0.8),
        (0.01,0.75,0.9,0.1),
        (0.09,0.95,0.5,-0.5)
    ]
    fig,axs=plt.subplots(3,2,figsize=(10,9))
    axs=axs.flatten()
    for ax,(nu,alpha,a,b) in zip(axs,setups):

        x_ref,u_ref=burgers_fd(nu,alpha,a,b)

        X=tf.constant(x_ref.reshape(-1,1),tf.float32)
        N=len(X)
        t=tf.ones([N,1],tf.float32)*T
        nu_t=tf.ones([N,1])*nu
        al_t=tf.ones([N,1])*alpha
        a_t=tf.ones([N,1])*a
        b_t=tf.ones([N,1])*b
        u_pred=model(t,X,nu_t,al_t,a_t,b_t).numpy().ravel()

        ax.plot(x_ref,u_ref,'b',lw=2,label='Finite difference (exact)')
        ax.plot(x_ref,u_pred,'r--',lw=1.5,label='DGM (deep learning)')
        ax.set_xlim(0,1)
        ax.set_title(f"(ν,α,a,b)=({nu:.2f},{alpha:.2f},{a:.2f},{b:.2f})")
    plt.tight_layout()
    plt.show()



