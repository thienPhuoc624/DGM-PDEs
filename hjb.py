import numpy as np
import tensorflow as tf
import matplotlib.pyplot as plt
import time


# Parameters

d = 21
L_domain = 0.1
Delta = L_domain / (d + 1)
alpha = 1e-4
sigma = np.sqrt(0.1)
_lambda = 1.0
gamma = 1.0
vbar = np.zeros(d, dtype=np.float32)

np.random.seed(42)
tf.random.set_seed(42)


# Discrete Laplacian D

def make_D(d):
    D = np.zeros((d, d), dtype=np.float32)
    for j in range(d):
        if j > 0:
            D[j, j-1] = 1.0
        D[j, j] = -2.0
        if j < d-1:
            D[j, j+1] = 1.0
    return D
D = make_D(d)


# Riccati semi-analytic solver

def solve_riccati(d, steps=8000, lr=3e-4):
    m = d*(d+1)//2
    P_entries = tf.Variable(tf.random.normal([m], stddev=0.01, dtype=tf.float32))
    b = tf.Variable(tf.zeros([d], dtype=tf.float32))
    c = tf.Variable(0.0, dtype=tf.float32)
    opt = tf.keras.optimizers.Adam(lr)

    def build_P_mat(entries):
        P = tf.zeros((d, d), dtype=tf.float32)
        idx = 0
        for i in range(d):
            for j in range(i, d):
                v = entries[idx]
                P = tf.tensor_scatter_nd_add(P, [[i, j]], [v])
                if i != j:
                    P = tf.tensor_scatter_nd_add(P, [[j, i]], [v])
                idx += 1
        return P

    @tf.function
    def step():
        with tf.GradientTape() as g:
            P = build_P_mat(P_entries)
            bcol = tf.reshape(b, (-1,1))
            termQ = (Delta*tf.eye(d, dtype=tf.float32)
                     - (1.0/(4.0*_lambda*Delta))*tf.matmul(P,P)
                     + (alpha/(Delta**2))*tf.matmul(tf.constant(D.T, dtype=tf.float32), P)
                     - 0.5*gamma*P)
            quad = 0.5*(termQ + tf.transpose(termQ))
            lin = - (1.0/(4.0*_lambda*Delta))*2.0*tf.squeeze(tf.matmul(P,bcol),1) \
                  + (alpha/(Delta**2))*tf.squeeze(tf.matmul(tf.constant(D.T, dtype=tf.float32),bcol),1) \
                  - 0.5*gamma*b
            const = - (1.0/(4.0*_lambda*Delta))*tf.reduce_sum(b*b) \
                    + (sigma**2/(2.0*Delta))*tf.linalg.trace(P) - gamma*c
            loss = tf.reduce_sum(quad**2) + tf.reduce_sum(lin**2) + const**2
        grads = g.gradient(loss, [P_entries,b,c])
        opt.apply_gradients(zip(grads,[P_entries,b,c]))
        return loss

    for k in range(steps):
        loss = step()
        if k % 500 == 0:
            print(f"[Riccati] step {k:5d} loss={loss.numpy():.2e}")

    P_np = np.zeros((d,d),np.float32)
    idx=0
    entries = P_entries.numpy()
    for i in range(d):
        for j in range(i,d):
            P_np[i,j]=P_np[j,i]=entries[idx]; idx+=1
    return P_np, b.numpy().astype(np.float32), float(c.numpy())


# DGM network definition

class DGMBlock(tf.keras.layers.Layer):
    def __init__(self,m):
        super().__init__()
        self.Uz=tf.keras.layers.Dense(m,activation='tanh')
        self.Ug=tf.keras.layers.Dense(m,activation='sigmoid')
        self.Ur=tf.keras.layers.Dense(m,activation='sigmoid')
        self.Uh=tf.keras.layers.Dense(m,activation='tanh')
        self.Wz=tf.keras.layers.Dense(m,use_bias=False)
        self.Wg=tf.keras.layers.Dense(m,use_bias=False)
        self.Wr=tf.keras.layers.Dense(m,use_bias=False)
        self.Wh=tf.keras.layers.Dense(m,use_bias=False)
    def call(self,x,S):
        Z=tf.tanh(self.Uz(x)+self.Wz(S))
        G=tf.sigmoid(self.Ug(x)+self.Wg(S))
        R=tf.sigmoid(self.Ur(x)+self.Wr(S))
        H=tf.tanh(self.Uh(x)+self.Wh(S*R))
        return (1-G)*H+Z*S

class DGMNet(tf.keras.Model):
    def __init__(self,d,m=100,nblocks=3):
        super().__init__()
        self.w1=tf.keras.layers.Dense(m,activation='tanh')
        self.blocks=[DGMBlock(m) for _ in range(nblocks)]
        self.wout=tf.keras.layers.Dense(1)
    def call(self,x):
        S=self.w1(x)
        for blk in self.blocks:
            S=blk(x,S)
        return tf.squeeze(self.wout(S),-1)




@tf.function
def pde_residual(model,x):
    def per_sample(xi):
        with tf.GradientTape(persistent=True) as g2:
            g2.watch(xi)
            with tf.GradientTape() as g1:
                g1.watch(xi)
                Vi=tf.squeeze(model(tf.expand_dims(xi,0)))
            grad=g1.gradient(Vi,xi)
        H=g2.jacobian(grad,xi)
        return Vi, grad, tf.linalg.diag_part(H)
    V,grad,diagH=tf.vectorized_map(per_sample,x)
    term1=0.5*Delta*tf.reduce_sum(x**2,1)
    term2=-(1/(4*_lambda*Delta))*tf.reduce_sum(grad**2,1)
    term3=(sigma**2/(2*Delta))*tf.reduce_sum(diagH,1)
    lap=[]
    for j in range(d):
        xp=x[:,j+1] if j+1<d else 0.0
        xm=x[:,j-1] if j-1>=0 else 0.0
        lap.append(xp-2*x[:,j]+xm)
    lap=tf.stack(lap,1)
    term4=(alpha/(Delta**2))*tf.reduce_sum(lap*grad,1)
    term5=-gamma*V
    res=term1+term2+term3+term4+term5
    return res,V

@tf.function
def loss_batch(model,x):
    res,V=pde_residual(model,x)
    loss=tf.reduce_mean(res**2)
    reg=1e-6*tf.add_n([tf.reduce_mean(v**2) for v in model.trainable_variables])
    return loss+reg

@tf.function
def train_step(model,opt,x):
    with tf.GradientTape() as g:
        L=loss_batch(model,x)
    grads=g.gradient(L,model.trainable_variables)
    opt.apply_gradients(zip(grads,model.trainable_variables))
    return L



def sample_x(n, d):
    return np.random.uniform(-7.5, 7.5, size=(n, d)).astype(np.float32)

def simulate_sde(U_func, n_samples=4000, n_steps=2000, dt=1e-5, clip=0.5):
    X = np.random.uniform(-7.5, 7.5, (n_samples, d)).astype(np.float32)
    sqrt_dt = np.sqrt(dt)
    B = sigma / np.sqrt(Delta)
    for _ in range(n_steps):
        lap = X @ D.T
        U = U_func(X)
        drift = (alpha/(Delta**2))*lap + U
        X += drift*dt + B*np.random.normal(size=X.shape).astype(np.float32)*sqrt_dt
    return X



def compute_avg_percent_error(model, P, b, c, n_eval=4000):
    def V_true(X):
        return 0.5*np.sum((X@P)*X,1)+X.dot(b)+c
    def U_true(X):
        return -(1.0/(2.0*_lambda*Delta))*(X@P.T+b)
    Xs = simulate_sde(U_true, n_samples=n_eval, n_steps=2000, dt=1e-5)
    preds = model(Xs).numpy().ravel()
    Vt = V_true(Xs)
    mask = np.abs(Vt) > 1e-8
    pct = np.abs(preds[mask]-Vt[mask])/np.abs(Vt[mask])*100
    return np.mean(pct)




def plot_percent_error(model, P, b, c):
    def V_true(X):
        return 0.5 * np.sum((X @ P) * X, axis=1) + X.dot(b) + c
    def U_true(X):
        return - (1.0/(2.0*_lambda*Delta)) * (X @ P.T + b)

    Xs = simulate_sde(U_true, n_samples=4000, n_steps=2000, dt=1e-5)
    preds = model(Xs).numpy().ravel()
    Vt = V_true(Xs)
    mask = np.abs(Vt) > 1e-8
    pct = np.abs(preds[mask] - Vt[mask]) / np.abs(Vt[mask]) * 100.0

    scale_factor = 1.0 / Delta
    x11 = Xs[mask, 10] * scale_factor
    xavg = np.mean(Xs[mask, :], axis=1) * scale_factor

    xi = np.linspace(-10, 10, 120)
    yi = np.linspace(-10, 10, 120)

    sums, xedges, yedges = np.histogram2d(x11, xavg, bins=[xi, yi], weights=pct)
    counts, _, _ = np.histogram2d(x11, xavg, bins=[xi, yi])
    mean_pct = np.zeros_like(sums.T)
    valid = counts.T > 0
    mean_pct[valid] = sums.T[valid] / counts.T[valid]

    Xi, Yi = np.meshgrid(0.5*(xedges[:-1]+xedges[1:]), 0.5*(yedges[:-1]+yedges[1:]))

    plt.figure(figsize=(7,5))
    cs = plt.contourf(Xi, Yi, mean_pct, levels=40, cmap='jet', extend='both')
    cbar = plt.colorbar(cs)
    cbar.set_label('Percent error (%)')
    plt.xlabel(r'$x_{11}$')
    plt.ylabel('Average of x')
    plt.tight_layout()
    plt.savefig('figure4_like.png', dpi=300)
    print("Saved as figure4_like.png")


# Learning rate schedule (α_n)

def get_lr(step):
    if step <= 5000:
        return 5e-4
    elif step <= 10000:
        return 5e-4
    elif step <= 20000:
        return 5e-4
    elif step <= 30000:
        return 5e-4
    elif step <= 40000:
        return 5e-4
    elif step <= 50000:
        return 5e-4
    else:
        return 1e-4



def main():
    t0 = time.time()
    print("Solving Riccati system ...")
    P,b,c = solve_riccati(d, steps=16000, lr=3e-4)
    print("Riccati solved. Beginning DGM training ...")

    model = DGMNet(d, m=100, nblocks=3)
    _ = model(tf.zeros((2,d)))
    opt = tf.keras.optimizers.Adam(learning_rate=get_lr(1))

    for step in range(1, 250000):
        opt.learning_rate.assign(get_lr(step))
        xb = sample_x(1024, d)
        L = train_step(model, opt, xb)

        if step % 500 == 0:
            avg_err = compute_avg_percent_error(model, P, b, c, n_eval=4000)
            lr_now = opt.learning_rate.numpy()
            print(f"[DGM] step {step:6d}  loss={L.numpy():.3e}  avg%err={avg_err:6.2f}  lr={lr_now:.1e}")

            if avg_err <= 7.0:
                print(f"\n Early stopping at step {step}: avg_err={avg_err:.2f}% < 7.0%")
                plot_percent_error(model, P, b, c)
                print(f"Total runtime: {time.time()-t0:.1f}s")
                return

    print("Training finished. Plotting result ...")
    plot_percent_error(model, P, b, c)
    print(f"Total runtime: {time.time()-t0:.1f}s")

if __name__=="__main__":
    main()