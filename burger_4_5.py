import numpy as np
import tensorflow as tf
import matplotlib.pyplot as plt

tf.keras.backend.set_floatx("float32")


T = 1.0
X_lo, X_hi = 0.0, 1.0

nu_range = [1e-2, 1e-1]
alpha_range = [1e-2, 1.0]
a_range, b_range = [-1.0, 1.0], [-1.0, 1.0]

def initial_condition(x, a, b):
    return a + (b - a) * x

def boundary_value(is_left, a, b):
    return is_left * a + (1.0 - is_left) * b


# Sampling

def sample_interior(N):
    t = tf.random.uniform([N, 1], 0.0, T)
    x = tf.random.uniform([N, 1], X_lo, X_hi)
    nu = tf.random.uniform([N, 1], *nu_range)
    alpha = tf.random.uniform([N, 1], *alpha_range)
    a = tf.random.uniform([N, 1], *a_range)
    b = tf.random.uniform([N, 1], *b_range)
    return t, x, nu, alpha, a, b

def sample_boundary(N):
    t = tf.random.uniform([N, 1], 0.0, T)
    is_left = tf.cast(tf.random.uniform([N, 1], 0, 1) > 0.5, tf.float32)
    x = is_left * X_lo + (1.0 - is_left) * X_hi
    nu = tf.random.uniform([N, 1], *nu_range)
    alpha = tf.random.uniform([N, 1], *alpha_range)
    a = tf.random.uniform([N, 1], *a_range)
    b = tf.random.uniform([N, 1], *b_range)
    return t, x, nu, alpha, a, b, is_left

def sample_initial(N):
    t = tf.zeros([N, 1], dtype=tf.float32)
    x = tf.random.uniform([N, 1], X_lo, X_hi)
    nu = tf.random.uniform([N, 1], *nu_range)
    alpha = tf.random.uniform([N, 1], *alpha_range)
    a = tf.random.uniform([N, 1], *a_range)
    b = tf.random.uniform([N, 1], *b_range)
    return t, x, nu, alpha, a, b




class DGMBlock(tf.keras.layers.Layer):
    def __init__(self, units):
        super().__init__()
        self.z = tf.keras.layers.Dense(units, activation="tanh")
        self.g = tf.keras.layers.Dense(units, activation="sigmoid")
        self.r = tf.keras.layers.Dense(units, activation="sigmoid")
        self.h = tf.keras.layers.Dense(units, activation="tanh")

    def call(self, X, S):
        Z = self.z(tf.concat([X, S], axis=1))
        G = self.g(tf.concat([X, S], axis=1))
        R = self.r(tf.concat([X, S], axis=1))
        H = self.h(tf.concat([X, R * S], axis=1))
        return (1.0 - G) * H + Z * S

class DGMNet(tf.keras.Model):
    def __init__(self, units=240, layers=6):
        super().__init__()
        self.first = tf.keras.layers.Dense(units, activation="tanh")
        self.blocks = [DGMBlock(units) for _ in range(layers)]
        self.out = tf.keras.layers.Dense(1, activation=None)

    def call(self, t, x, nu, alpha, a, b):
        X = tf.concat([t, x, nu, alpha, a, b], axis=1)
        S = self.first(X)
        for blk in self.blocks:
            S = blk(X, S)
        return self.out(S)


# PDE residual: u_t - nu u_xx + alpha u u_x

def residual(model, t, x, nu, alpha, a, b):
    with tf.GradientTape(persistent=True) as t2:
        t2.watch([t, x])
        with tf.GradientTape(persistent=True) as t1:
            t1.watch([t, x])
            u = model(t, x, nu, alpha, a, b)
        u_t = t1.gradient(u, t)
        u_x = t1.gradient(u, x)
    u_xx = t2.gradient(u_x, x)
    del t1, t2
    return u_t - nu * u_xx + alpha * u * u_x


# Loss

def compute_loss(model, Ni, Nb, No):
    t_i, x_i, nu_i, al_i, a_i, b_i = sample_interior(Ni)
    r = residual(model, t_i, x_i, nu_i, al_i, a_i, b_i)
    loss_pde = tf.reduce_mean(tf.square(r))

    t_b, x_b, nu_b, al_b, a_b, b_b, left = sample_boundary(Nb)
    u_b = model(t_b, x_b, nu_b, al_b, a_b, b_b)
    u_bv = boundary_value(left, a_b, b_b)
    loss_bnd = tf.reduce_mean(tf.square(u_b - u_bv))

    t0, x0, nu0, al0, a0, b0 = sample_initial(No)
    u0 = model(t0, x0, nu0, al0, a0, b0)
    g0 = initial_condition(x0, a0, b0)
    loss_ini = tf.reduce_mean(tf.square(u0 - g0))

    return loss_pde + loss_bnd + loss_ini


# Training

def train(model, steps=10000, lr=5e-4, Ni=2048, Nb=512, No=512, print_every=1000):
    opt = tf.keras.optimizers.Adam(learning_rate=lr)
    for step in range(steps):
        with tf.GradientTape() as tape:
            loss = compute_loss(model, Ni, Nb, No)
        grads = tape.gradient(loss, model.trainable_variables)
        opt.apply_gradients(zip(grads, model.trainable_variables))
        if step % print_every == 0:
            print(f"Step {step:6d} | loss={loss.numpy():.4e}")




def burgers_fd_time(nu, alpha, a, b, t_target, Nx=400):
    x = np.linspace(0.0, 1.0, Nx, dtype=np.float64)
    dx = x[1] - x[0]
    u = a + (b - a) * x

    eps = 1e-12
    dt_diff = 0.25 * dx * dx / (nu + eps)
    dt_conv = 0.4 * dx / (alpha * (np.max(np.abs(u)) + eps) + eps)
    dt = min(dt_diff, dt_conv)

    Nt = max(1, int(np.ceil(t_target / dt)))
    dt = t_target / Nt

    u_new = u.copy()
    for _ in range(Nt):
        uxx = (u[2:] - 2.0 * u[1:-1] + u[:-2]) / (dx * dx)
        ux = (u[2:] - u[:-2]) / (2.0 * dx)
        u_new[1:-1] = u[1:-1] + dt * (nu * uxx - alpha * u[1:-1] * ux)
        u_new[0] = a
        u_new[-1] = b
        u, u_new = u_new, u

    return x.astype(np.float32), u.astype(np.float32)




def plot_fig7(model,
              ALPHA_FIXED=0.95,
              A_FIXED=0.90,
              b_vals=None,
              nu_vals=None,
              Nx_eval=400):

    if b_vals is None:
        b_vals = np.linspace(-1.0, 1.0, 41, dtype=np.float32)
    if nu_vals is None:
        nu_vals = np.linspace(0.01, 0.10, 31, dtype=np.float32)

    Err = np.zeros((len(nu_vals), len(b_vals)), dtype=np.float32)

    x_grid = np.linspace(0.0, 1.0, Nx_eval, dtype=np.float32).reshape(-1, 1)
    X_tf = tf.constant(x_grid, dtype=tf.float32)
    N = Nx_eval

    for i, nu in enumerate(nu_vals):
        for j, b in enumerate(b_vals):

            x_ref, u_ref = burgers_fd_time(float(nu), float(ALPHA_FIXED),
                                           float(A_FIXED), float(b),
                                           t_target=T, Nx=Nx_eval)


            t_tf = tf.ones([N, 1], dtype=tf.float32) * T
            nu_tf = tf.ones([N, 1], dtype=tf.float32) * float(nu)
            al_tf = tf.ones([N, 1], dtype=tf.float32) * float(ALPHA_FIXED)
            a_tf  = tf.ones([N, 1], dtype=tf.float32) * float(A_FIXED)
            b_tf  = tf.ones([N, 1], dtype=tf.float32) * float(b)

            u_pred = model(t_tf, X_tf, nu_tf, al_tf, a_tf, b_tf).numpy().reshape(-1)

            Err[i, j] = float(np.mean(np.abs(u_pred - u_ref.reshape(-1))))

        print(f"Computed row {i+1}/{len(nu_vals)} for nu={nu:.4f}")

    B, NU = np.meshgrid(b_vals, nu_vals)

    plt.figure(figsize=(7.5, 5.5))
    cf = plt.contourf(B, NU, Err, levels=20)
    plt.colorbar(cf, label="Avg absolute error over x at t=1")
    plt.xlabel("b")
    plt.ylabel("ν")
    plt.title(f"Fig 7-style: avg |u_DGM - u_FD| over x at t=1\n(fixed α={ALPHA_FIXED}, a={A_FIXED})")
    plt.tight_layout()
    plt.show()




if __name__ == "__main__":
    model = DGMNet(units=240, layers=6)
    dummy = [tf.zeros([1, 1], dtype=tf.float32) for _ in range(6)]
    _ = model(*dummy)
    print("Training Burgers DGM network ...")
    train(model, steps=10000, lr=5e-4, Ni=2048, Nb=512, No=512, print_every=1000)
    print("Plotting Figure 7 (contour of avg abs error) ...")
    plot_fig7(model, ALPHA_FIXED=0.95, A_FIXED=0.90)